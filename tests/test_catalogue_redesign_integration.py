import copy
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import catalogue_redesign


class CatalogueRedesignIntegrationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.data = json.loads(catalogue_redesign.ASSESSMENTS.read_text(encoding="utf-8"))
        cls.context = catalogue_redesign.contract_data()

    def test_integrated_sources_cover_every_root_pin_once(self):
        records = catalogue_redesign.validate_dataset(self.data, self.context)
        _, _, pins, paths, _ = self.context
        self.assertEqual([record["path"] for record in records], paths)
        self.assertEqual(len(records), 73)
        self.assertTrue(all(record["source_pin"] == pins[record["path"]] for record in records))

    def test_integrated_contributions_remain_nested_in_one_project_source(self):
        records = catalogue_redesign.validate_dataset(self.data, self.context)
        self.assertEqual(sum(len(record["contributions"]) for record in records), 68)
        for record in records:
            self.assertEqual(set(record["project"]["judgements"]), {
                "current_product_value", "future_product_value",
                "technical_feasibility", "delivery_feasibility",
            })
            self.assertTrue(all(set(card["judgements"]) == {
                "non_obviousness", "depth_of_thought", "transferability",
                "current_contribution_value", "future_contribution_value",
            } for card in record["contributions"]))

    def test_integrated_dataset_rejects_missing_duplicate_and_unpinned_records(self):
        cases = [
            lambda data: data["assessments"].pop(),
            lambda data: data["assessments"].__setitem__(-1, copy.deepcopy(data["assessments"][0])),
            lambda data: data["assessments"][0].__setitem__("source_pin", "0" * 40),
        ]
        for mutate in cases:
            with self.subTest(mutate=mutate):
                sample = copy.deepcopy(self.data)
                mutate(sample)
                with self.assertRaises(ValueError):
                    catalogue_redesign.validate_dataset(sample, self.context)

    def test_integrated_view_discloses_incomplete_comparisons_and_pending_review(self):
        view = catalogue_redesign.VIEW.read_text(encoding="utf-8")
        self.assertIn("Not M1 acceptance", view)
        self.assertIn("Public-A evidence remains incomplete", view)
        self.assertIn("public-B is blocked", view)
        self.assertIn("fresh independent review is pending", view)
        self.assertIn("Generated by scripts/catalogue_redesign.py", view)

    def test_owner_testimony_kept_distinct_from_agent_inference(self):
        records = {record["path"]: record for record in self.data["assessments"]}
        for path in ("agentic-animation", "auto_maintain_bench", "aps", "hyperframaker", "horse_video", "huaqiang_video"):
            with self.subTest(path=path):
                self.assertTrue(any(
                    item["provenance"] == "owner_testimony"
                    for item in records[path]["evidence"]
                ))
        hyper = records["hyperframaker"]
        owner_item = next(item for item in hyper["evidence"] if item["provenance"] == "owner_testimony")
        self.assertIn("at most around APS", owner_item["claim"])
        self.assertTrue(all(value["status"] == "unknown" for value in hyper["contributions"][0]["judgements"].values()))
        agentic = records["agentic-animation"]
        pipeline = next(card for card in agentic["contributions"] if card["id"] == "agentic-animation:documented-story-pipeline")
        self.assertEqual(pipeline["judgements"]["non_obviousness"]["estimate"], 4)
        self.assertIn("documented-story-pipeline", {item["id"] for item in agentic["evidence"]})


if __name__ == "__main__":
    unittest.main()
