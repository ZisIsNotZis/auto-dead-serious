#!/usr/bin/env python3
"""Render what is waiting on the person, from the root's own outbox.

    python3 tools/needs.py            write docs/needs-you.md
    python3 tools/needs.py --check    refuse a render that no longer matches the outbox

A message to the person is one file in docs/outbox. Its first lines are `kind:`, `spend:`,
`from:`, and the rest is the question. The order is what the person would regret leaving
longest, not what arrived first.
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
OUTBOX = HERE / "docs" / "outbox"
OUT = HERE / "docs" / "needs-you.md"

RANK = {("cost", "money"): 1, ("resource", "money"): 1, ("resource", "gpu"): 1,
        ("direction", "taste"): 2}


def field(text: str, name: str) -> str:
    for line in text.splitlines():
        if line.lower().startswith(f"{name}:"):
            return line.split(":", 1)[1].strip()
    return "unknown"


def items() -> list[dict]:
    found = []
    if not OUTBOX.exists():
        return found
    for f in sorted(OUTBOX.glob("*.md")):
        if f.name == "README.md":
            continue
        text = f.read_text(encoding="utf-8")
        kind, spend = field(text, "kind"), field(text, "spend")
        found.append({"id": f.stem, "kind": kind, "spend": spend,
                      "from": field(text, "from"),
                      "effort": "## effort" in text.lower(),
                      "rank": RANK.get((kind, spend), 3)})
    return sorted(found, key=lambda i: (i["rank"], i["id"]))


def render(found: list[dict]) -> str:
    lines = ["# Needs you", "",
             "Generated by `tools/needs.py` from `docs/outbox/`. Read this instead of scrolling back.", ""]
    if not found:
        lines.append("Nothing is waiting on the person.")
        return "\n".join(lines) + "\n"
    lines += [f"{len(found)} waiting.", "",
              "| rank | id | kind | spends | from | effort |", "|---|---|---|---|---|---|"]
    for i in found:
        lines.append(f"| {i['rank']} | `{i['id']}` | {i['kind']} | {i['spend']} | {i['from']} | "
                     f"{'yes' if i['effort'] else 'BOUNCE'} |")
    lines += ["", "A row whose effort is BOUNCE has not earned its place and goes back to its sender."]
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render(items())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("FAIL needs-you.md does not match the outbox")
            return 1
        print("ok: needs-you.md matches the outbox")
        return 0
    OUTBOX.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(HERE)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
