#!/usr/bin/env python3
"""Render the list of what is waiting on the person.

    python3 tools/needs.py            write docs/needs-you.md
    python3 tools/needs.py --check    refuse a render that no longer matches the inbox

An item is a directory under docs/raise with an ask.md. Its first lines are `kind:`,
`spend:` and `from:`. Ordering is by what the person would regret leaving longest, not by
age: a decision taken in their absence comes first, then anything that spent money or lost
work, then a question that expires, then the rest.
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
RAISE = HERE / "docs" / "raise"
OUT = HERE / "docs" / "needs-you.md"

RANK = {
    ("cost", "money"): 1, ("resource", "money"): 1, ("cost", "gpu"): 1,
    ("direction", "taste"): 2, ("resource", "gpu"): 1, ("resource", "disk"): 1,
}


def field(text: str, name: str) -> str:
    for line in text.splitlines():
        if line.lower().startswith(f"{name}:"):
            return line.split(":", 1)[1].strip()
    return "unknown"


def items() -> list[dict]:
    found = []
    for d in sorted(RAISE.glob("*/")):
        ask = d / "ask.md"
        if not ask.exists():
            continue
        text = ask.read_text(encoding="utf-8")
        kind, spend = field(text, "kind"), field(text, "spend")
        notes = d / "notes.tsv"
        touched = len(notes.read_text(encoding="utf-8").strip().splitlines()) if notes.exists() else 0
        found.append({
            "id": d.name,
            "kind": kind,
            "spend": spend,
            "from": field(text, "from"),
            "effort": (d / "effort.md").exists(),
            "touched": touched,
            "rank": RANK.get((kind, spend), 3),
        })
    return sorted(found, key=lambda i: (i["rank"], i["id"]))


def render(found: list[dict]) -> str:
    lines = [
        "# Needs you",
        "",
        "Generated by `tools/needs.py` from `docs/raise/`. Read this instead of scrolling back.",
        "",
    ]
    if not found:
        lines.append("Nothing is waiting on the person.")
        return "\n".join(lines) + "\n"
    lines += [f"{len(found)} waiting.", "",
              "| rank | id | kind | spends | from | effort | layers |", "|---|---|---|---|---|---|---|"]
    for i in found:
        lines.append(
            f"| {i['rank']} | `{i['id']}` | {i['kind']} | {i['spend']} | {i['from']} | "
            f"{'yes' if i['effort'] else 'BOUNCE'} | {i['touched']} |")
    lines += ["", "A row whose effort is BOUNCE has not earned its place and goes back to its sender."]
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render(items())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("FAIL needs-you.md does not match the inbox")
            return 1
        print("ok: needs-you.md matches the inbox")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(HERE)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
