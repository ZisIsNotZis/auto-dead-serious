#!/usr/bin/env python3
"""Derive showcase axes from the practical estimates and render the gallery and its appendix.

Reads docs/result/catalogue-redesign/assessments.json (authored source of the estimates and of
each project's display text) and writes README.md and index.html beside it. Nothing here invents
a fact: every displayed string is either authored in assessments.json or composed from it.
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HOME = ROOT / "docs/result/catalogue-redesign"
SOURCE = HOME / "assessments.json"
PRIVATE = {"colleague_private", "tutor_private", "resume_private"}
FAMILIES = {
    "myminio": "storage-toys", "myminio2": "storage-toys", "myygo": "storage-toys",
    "ygo": "storage-toys", "myzcopy": "storage-toys", "xywdisk": "storage-toys",
    "disk": "storage-toys", "vibeos": "storage-toys",
    "cz_bert": "cz-experiments", "cz_einn": "cz-experiments", "cz_noidea": "cz-experiments", "cznn": "cz-experiments",
    "resume_private": "resume-tooling", "resume_img_gen": "resume-tooling", "resume_improve_loop": "resume-tooling",
    "horse_video": "one-off-video", "huaqiang_video": "one-off-video",
    "sys_gal": "story-engine", "sys_gal_rt": "story-engine",
    "myminio2b": "storage-toys",
}
WEIGHTS = {"idea": 0.40, "realized": 0.35, "upside": 0.25}
FLOOR = 0.5


def est(a, key):
    return a["project"]["judgements"][key]["estimate"]


def strongest(a):
    return max(a["contributions"], key=lambda c: (c["judgements"]["current_contribution_value"]["estimate"], c["judgements"]["depth_of_thought"]["estimate"]), default=None)


def axes(a):
    """Four display axes; correlated columns are collapsed, not summed."""
    idea = a["display"]["idea"]
    i = sum(idea.values()) / 3
    p = [est(a, k) for k in ("current_product_value", "future_product_value", "technical_feasibility", "delivery_feasibility")]
    c = strongest(a)
    inside_now = c["judgements"]["current_contribution_value"]["estimate"] if c else 0
    inside_next = c["judgements"]["future_contribution_value"]["estimate"] if c else 0
    realized = max(p[0], inside_now)
    upside = max(p[1], inside_next) * (p[2] + p[3]) / 20
    base = i ** WEIGHTS["idea"] * (realized + FLOOR) ** WEIGHTS["realized"] * (upside + FLOOR) ** WEIGHTS["upside"]
    gate = a["display"]["showability"]["gate"]
    return {"idea": i, "realized": realized, "upside": upside, "delivery": p[3], "gate": gate, "showcase": gate * base}


def anchor(path):
    return re.sub(r"[^a-z0-9]+", "-", path.lower()).strip("-")


def render(data):
    records = data["assessments"]
    for a in records:
        a["display"]["family"] = a["display"].get("family") or FAMILIES.get(a["path"], a["path"])
        a["_x"] = axes(a)
    order = sorted(records, key=lambda a: (-a["_x"]["showcase"], a["path"].lower()))
    best_in_family = {}
    for a in order:
        best_in_family.setdefault(a["display"]["family"], a)

    def cell(a):
        x = a["_x"]
        return [f"{x['showcase']:.1f}", f"{x['idea']:.1f}", f"{x['realized']:.0f}", f"{x['upside']:.1f}", f"{x['delivery']:.0f}", f"{x['gate']:g}"]

    lines = [
        "<!-- Generated by scripts/catalogue_final.py from assessments.json; edit the source, not this view. -->",
        "# Project gallery",
        "A stranger's question is not *is this useful to me* but *does this show what the author can do*. This table answers the second one. All scores are ordinal 0–10 judgement estimates, never measurements.",
        "",
        "## How to read it",
        f"**Showcase** is the recommendation level for a generic newcomer: `gate × idea^{WEIGHTS['idea']} × (realized+{FLOOR})^{WEIGHTS['realized']} × (upside+{FLOOR})^{WEIGHTS['upside']}`. A weighted geometric mean, so no single column carries a project and a weak factor degrades instead of being averaged away.",
        "- **idea** — mean of non-obviousness, depth of thought and transferability, judged **blind to whether the thing runs**. An unbuilt design with sharp reasoning scores high here and low on realized.",
        "- **realized** — `max(product value now, best inside asset value now)`. Max, not sum: an artefact is not paid twice for being both a product and a contribution.",
        "- **upside** — `max(future product, future inside) × (technical+delivery)/20`. Conditional on the stated scope succeeding, then discounted by whether it can plausibly be finished.",
        "- **delivery** — ordinal likelihood a complete presentable thing exists, given the actual state and remaining scope.",
        "- **gate** — 1 if a stranger can open it and see something, 0 if not (private payload, nothing runnable, or a one-off with no reusable method). Binary on purpose: an unfinished or setup-heavy project already loses points in `delivery`, and pricing the same caveat twice would punish it twice. Multiplicative, because a 10/10 idea in a repository nobody may open has no showcase value.",
        "",
        "Three columns were collapsed from the earlier nine because they are not independent measurements. `now`↔`inside now` (r≈0.86) and `future`↔`inside future` (r≈0.88) are structurally nested: the inside figure is the best asset *within* the product, so summing them pays the same artefact twice. The three idea dimensions are a different case, and it was measured rather than assumed: a divergence-forcing re-score of 21 projects — each dimension argued from separate evidence, idea judged blind to delivery state — still returns r=0.93 (non-obviousness~depth), 0.94 (depth~transferability) and 0.94 (non-obviousness~transferability), against 0.93/0.85/0.86 for the 52 projects scored in one blended pass. The fusion is intrinsic to the question, not sloppiness in the first pass, so idea enters the formula once instead of three times. The per-dimension numbers stay in every appendix entry so the finding can be checked rather than trusted.",
        "",
        "## What this table is not",
        "Ordinal estimates from written evidence, not measurements: no build, test, render or model run backs any number here, and no effort quantity is claimed. Where a packet supplied a single project-level rationale, that sentence is shown against each of the four project axes rather than paraphrased into invented distinctions — only the audits carry per-axis evidence. Private repositories were deliberately not inspected, so their zeros mean *not shown*, never *not worth doing*. The audit that corrected the bottom of the scale covered 21 of 73 projects; the rest keep their original estimate and are marked by the absence of an audit line in their trajectory.",
        "",
        "## Gallery",
        "| Project | What it is | State | Showcase | Idea | Realized | Upside | Delivery | Gate | Strongest asset inside |",
        "|---|---|---|---:|---:|---:|---:|---:|---:|---|",
    ]
    for a in order:
        d = a["display"]
        lines.append(f"| [{a['path']}](#{anchor(a['path'])}) | {d['what']} | {d['state']} | " + " | ".join(cell(a)) + f" | {d['asset'] or '—'} |")
    lines += ["", "## What to show first", "One per family, so a portfolio is not six variants of the same idea. Order is showcase score.", ""]
    for fam, a in sorted(best_in_family.items(), key=lambda kv: -kv[1]["_x"]["showcase"])[:12]:
        lines.append(f"- **{a['path']}** ({a['_x']['showcase']:.1f}, {a['display']['state']}) — {a['display']['what']}")
    lines += ["", "## Appendix", "One section per project: what you see, how each number was reached, what is unverified, and how the rating moved."]
    for a in order:
        d = a["display"]
        x = a["_x"]
        lines += ["", f'<a id="{anchor(a["path"])}"></a>', f"### {a['path']}", d["what"], "",
                  f"**State** {d['state']} · **Showcase** {x['showcase']:.1f} · **Gate** {x['gate']:g} — {d['showability']['reason']}",
                  f"**Who it is for** {d['for']}"]
        if d.get("hook"):
            lines.append(f"**What to keep in mind** {d['hook']}")
        if d.get("asset"):
            lines.append(f"**Strongest reusable thing inside** {d['asset']}")
        lines.append("")
        lines.append("**What you see**")
        lines += [f"- {item}" for item in d["see"]]
        lines += ["", "**How the numbers were reached**", "| Axis | Score | Derivation |", "|---|---:|---|",
                  f"| idea | {x['idea']:.1f} | " + d["why"]["idea"] + " |",
                  f"| realized | {x['realized']:.0f} | " + d["why"]["realized"] + " |",
                  f"| upside | {x['upside']:.1f} | " + d["why"]["upside"] + " |",
                  f"| delivery | {x['delivery']:.0f} | " + d["why"]["delivery"] + " |"]
        lines += ["", "**Unverified or bounded**"]
        lines += [f"- {item}" for item in a["limitations"][:4]]
        lines += ["", "**Rating trajectory**"]
        lines += [f"- {item}" for item in d["trajectory"]]
        if a["contributions"]:
            lines += ["", "**Assets inside**", "| Asset | Non-obvious | Depth | Transfer | Now | If done | Why |", "|---|---:|---:|---:|---:|---:|---|"]
            for c in a["contributions"]:
                j = c["judgements"]
                lines.append(f"| {c['id'].split(':', 1)[-1]} | {j['non_obviousness']['estimate']} | {j['depth_of_thought']['estimate']} | {j['transferability']['estimate']} | {j['current_contribution_value']['estimate']} | {j['future_contribution_value']['estimate']} | {j['current_contribution_value']['rationale']} |")
    (HOME / "README.md").write_text("\n".join(lines) + "\n")

    rows = []
    for a in order:
        d, x = a["display"], a["_x"]
        det = (f"<p><b>What you see</b></p><ul>" + "".join(f"<li>{html.escape(i)}</li>" for i in d["see"]) + "</ul>"
               "<p><b>How the numbers were reached</b></p><ul>"
               + "".join(f"<li><b>{k}</b> {float(v):.1f} — {html.escape(d['why'][k])}</li>" for k, v in (("idea", x["idea"]), ("realized", x["realized"]), ("upside", x["upside"]), ("delivery", x["delivery"])))
               + f"</ul><p><b>Gate</b> {x['gate']:g} — {html.escape(d['showability']['reason'])}</p>"
               + "<p><b>Unverified</b></p><ul>" + "".join(f"<li>{html.escape(i)}</li>" for i in a["limitations"][:4]) + "</ul>"
               + "<p><b>Rating trajectory</b></p><ul>" + "".join(f"<li>{html.escape(i)}</li>" for i in d["trajectory"]) + "</ul>")
        rows.append("<tr><td><details><summary><b>" + html.escape(a["path"]) + "</b><small>" + html.escape(d["what"]) + "</small><em>" + html.escape(d["asset"] or "—") + "</em></summary>" + det + "</details></td>"
                    + "".join(f"<td>{html.escape(c)}</td>" for c in [d["state"], f"{x['showcase']:.1f}", f"{x['idea']:.1f}", f"{x['realized']:.0f}", f"{x['upside']:.1f}", f"{x['delivery']:.0f}", f"{x['gate']:g}"]) + "</tr>")
    page = """<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Project gallery</title>
<style>body{font:15px/1.5 system-ui;margin:24px;background:#0f172a;color:#e2e8f0;max-width:1400px}input{padding:12px;width:min(560px,90%);margin:10px 0;background:#1e293b;color:#e2e8f0;border:1px solid #334155;border-radius:6px}
table{border-collapse:collapse;width:100%}th,td{padding:8px 10px;border-bottom:1px solid #334155;text-align:left;vertical-align:top}th{cursor:pointer;position:sticky;top:0;background:#1e293b;font-size:13px;white-space:nowrap}
td:not(:first-child){text-align:center}small{display:block;color:#94a3b8;font-weight:400;font-size:12px}em{display:block;color:#7dd3fc;font-size:12px;font-style:normal}details summary{cursor:pointer}a{color:#93c5fd}
td ul{margin:4px 0 8px 18px;padding:0}td p{margin:8px 0 2px;color:#94a3b8;font-size:12px;text-transform:uppercase;letter-spacing:.04em}</style>
<h1>Project gallery</h1><p>Ordinal 0–10 judgement estimates, not measurements. <b>Showcase</b> = gate × idea^0.40 × (realized+0.5)^0.35 × (upside+0.5)^0.25. Click a row for what you see, how each number was reached, and what stays unverified. Click a heading to sort.</p>
<input id="filter" placeholder="Filter by project, text, tag or state"><table><thead><tr><th>Project / detail</th><th>State</th><th>Showcase</th><th>Idea</th><th>Realized</th><th>Upside</th><th>Delivery</th><th>Gate</th></tr></thead><tbody>
""" + "".join(rows) + """</tbody></table>
<script>const t=document.querySelector('tbody');document.querySelector('#filter').oninput=e=>{const v=e.target.value.toLowerCase();for(const r of t.rows)r.hidden=!r.textContent.toLowerCase().includes(v)};
let column=-1,ascending=false;document.querySelectorAll('th').forEach((h,i)=>h.onclick=()=>{ascending=column===i?!ascending:false;column=i;const rows=[...t.rows];
rows.sort((a,b)=>{const x=a.cells[i].textContent.trim(),y=b.cells[i].textContent.trim();if(i>0&&i<8){return (Number(x)-Number(y))*(ascending?1:-1)}return x.localeCompare(y)*(ascending?1:-1)});rows.forEach(r=>t.appendChild(r))});</script></html>"""
    (HOME / "index.html").write_text(page)
    print(f"PASS: {len(records)} projects, {len(order)} rows rendered, showcase {order[0]['path']} {order[0]['_x']['showcase']:.1f} → {order[-1]['path']} {order[-1]['_x']['showcase']:.1f}")


if __name__ == "__main__":
    render(json.loads(SOURCE.read_text()))
