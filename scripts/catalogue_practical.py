#!/usr/bin/env python3
"""Adopt one-project practical estimates and render the existing catalogue, without research gates."""
import argparse
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HOME = ROOT / "docs/result/catalogue-redesign"
SOURCE = HOME / "assessments.json"
PROJECT = ("current_product_value", "future_product_value", "technical_feasibility", "delivery_feasibility")
CONTRIBUTION = ("non_obviousness", "depth_of_thought", "transferability", "current_contribution_value", "future_contribution_value")
COLUMNS = ("Insight", "Depth", "Transfer", "Product now", "Product if done", "Inside now", "Inside if done", "Technical", "Delivery")


def parse(path):
    raw = path.read_text().strip()
    if raw.startswith("```json") and raw.endswith("```"):
        raw = raw[7:-3].strip()
    return json.loads(raw)


def numbers(scores, keys):
    assert set(scores) == set(keys), f"wrong score fields: {set(scores)}"
    assert all(type(scores[k]) is int and 0 <= scores[k] <= 10 for k in keys), "score must be integer 0–10"


def estimate(value, reason, confidence):
    return {"status": "estimated", "estimate": value, "scale": "ordinal_0_10", "rationale": reason, "confidence": confidence, "basis": "practical judgement from supplied existing evidence; not a measurement"}


def merge(directories):
    data = parse(SOURCE)
    by_path = {a["path"]: a for a in data["assessments"]}
    results = {}
    for directory in directories:
        for file in sorted(Path(directory).glob("*.json")):
            score = parse(file)
            path = score["path"]
            assert path in by_path and path not in results, f"unexpected or duplicate project: {path}"
            numbers(score["project_scores"], PROJECT)
            expected_ids = {c["id"] for c in by_path[path]["contributions"]}
            assert len(score["contributions"]) == len(expected_ids)
            assert {c["id"] for c in score["contributions"]} == expected_ids, f"contribution ids differ: {path}"
            for c in score["contributions"]:
                numbers(c["scores"], CONTRIBUTION)
            assert score["confidence"] in {"low", "medium", "high"}
            results[path] = score
    missing = set(by_path) - set(results)
    assert not missing, f"Still awaiting {len(missing)} project results: {', '.join(sorted(missing))}"
    for path, a in by_path.items():
        score = results[path]
        a["project"]["judgements"] = {key: estimate(value, score["reason"], score["confidence"]) for key, value in score["project_scores"].items()}
        by_id = {c["id"]: c for c in score["contributions"]}
        for c in a["contributions"]:
            result = by_id[c["id"]]
            c["judgements"] = {key: estimate(value, result["reason"], score["confidence"]) for key, value in result["scores"].items()}
        a["rating_assumption"] = score.get("assumption", "")
        a["rating_method"] = "one-project practical estimate; no new research or verification"
    data["contract_version"] = "practical-estimates-v1"
    data["rating_semantics"] = "All nine scores are ordinal 0–10 judgement estimates; feasibility is not a statistical probability. Conditional future value is total value if the stated goal succeeds. Actual effort quantities are not invented."
    SOURCE.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    return data


def row(a):
    contributions = a["contributions"]
    strongest = max(contributions, key=lambda c: (c["judgements"]["current_contribution_value"]["estimate"], c["judgements"]["depth_of_thought"]["estimate"]), default=None)
    values = [strongest["judgements"][k]["estimate"] if strongest else 0 for k in CONTRIBUTION]
    p = a["project"]["judgements"]
    return [*values[:3], p["current_product_value"]["estimate"], p["future_product_value"]["estimate"], *values[3:], p["technical_feasibility"]["estimate"], p["delivery_feasibility"]["estimate"]]


def render(data):
    records = sorted(data["assessments"], key=lambda a: a["path"].lower())
    lines = ["<!-- Generated by scripts/catalogue_practical.py from assessments.json; edit the source, not this view. -->", "# Project ratings", "**Practical estimates, 0–10—not measurements. Every project has numerical scores.**", "Insight, depth and transfer refer to the strongest currently valuable contribution, not code volume. Inside value is reusable value distinct from the product; zero means no separately valuable contribution was identified in the supplied assessment.", "Future value means total value **if the stated goal succeeds**, not probability-weighted value. Technical and delivery are ordinal plausibility judgements, not statistical forecasts. Confidence and short reasons are in the linked cards. No overall average is used.", "[Sortable local table](index.html) · [Full source and reasons](assessments.json)", "| Project | " + " | ".join(COLUMNS) + " |", "|---|" + "---:|" * len(COLUMNS)]
    for a in records:
        lines.append("| [" + a["path"] + "](#" + a["path"].replace(".", "-").replace("_", "-").lower() + ") | " + " | ".join(map(str, row(a))) + " |")
    for a in records:
        anchor = a["path"].replace(".", "-").replace("_", "-").lower()
        lines += ['<a id="' + anchor + '"></a>', "## " + a["path"], a["project"]["description"], a["project"]["judgements"]["current_product_value"]["rationale"]]
        if a.get("rating_assumption"):
            lines.append("Assumption: " + a["rating_assumption"])
        for c in a["contributions"]:
            lines.append("- **" + c["id"].split(":", 1)[-1] + "** — " + c["judgements"]["depth_of_thought"]["rationale"])
    (HOME / "README.md").write_text("\n".join(lines) + "\n")
    body = []
    for a in records:
        description = html.escape(a["project"]["description"])
        reason = html.escape(a["project"]["judgements"]["current_product_value"]["rationale"])
        body.append('<tr><td title="' + description + '"><strong>' + html.escape(a["path"]) + '</strong><small>' + description + '</small></td>' + ''.join('<td>'+str(n)+'</td>' for n in row(a)) + '<td>'+reason+'</td></tr>')
    page = '''<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Project ratings</title><style>body{font:15px system-ui;margin:24px;background:#111827;color:#e5e7eb}input{padding:12px;width:min(550px,90%);margin:12px 0}table{border-collapse:collapse;width:100%}th,td{padding:10px;border-bottom:1px solid #374151;text-align:left}th{cursor:pointer;position:sticky;top:0;background:#1f2937}td:not(:first-child):not(:last-child){text-align:center}small{display:block;max-width:420px;color:#9ca3af;font-size:12px}a{color:#93c5fd}</style><h1>Project ratings</h1><p>0–10 practical judgement estimates, not measurements. Click a heading to sort. Future value is conditional on completing the goal; feasibility is ordinal, not probability.</p><input id="filter" placeholder="Filter projects or descriptions"><table><thead><tr>'''
    page += ''.join('<th>'+html.escape(c)+'</th>' for c in ('Project', *COLUMNS, 'Reason')) + '</tr></thead><tbody>' + ''.join(body) + '</tbody></table>'
    page += '''<script>const t=document.querySelector('tbody');document.querySelector('#filter').oninput=e=>{for(const r of t.rows)r.hidden=!r.textContent.toLowerCase().includes(e.target.value.toLowerCase())};let column=-1,ascending=false;document.querySelectorAll('th').forEach((h,i)=>h.onclick=()=>{ascending=column===i?!ascending:false;column=i;const rows=[...t.rows];rows.sort((a,b)=>{const x=a.cells[i].textContent,y=b.cells[i].textContent;return (i>0&&i<10?Number(x)-Number(y):x.localeCompare(y))*(ascending?1:-1)});rows.forEach(r=>t.appendChild(r))});</script></html>'''
    (HOME / "index.html").write_text(page)
    count = sum(len(PROJECT) + len(CONTRIBUTION) * len(a["contributions"]) for a in records)
    print(f"PASS: {len(records)} projects, {count} numeric source judgements; {len(records)*9} displayed numeric scores; no unknown score cells")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--merge", nargs="+")
    parser.add_argument("--render", action="store_true")
    args = parser.parse_args()
    data = merge(args.merge) if args.merge else parse(SOURCE)
    if args.merge or args.render:
        render(data)
    else:
        parser.error("choose --merge DIRECTORIES or --render")


if __name__ == "__main__":
    main()
